def add(a,b,n): return tuple((x+y)%n for x,y in zip(a,b))
def sub(a,b,n): return tuple((x-y)%n for x,y in zip(a,b))
def closure(gens,n,N):
    S={tuple([0]*N)}; frontier=list(S)
    while frontier:
        new=[]
        for s in frontier:
            for g in gens:
                t=add(s,g,n)
                if t not in S: S.add(t); new.append(t)
        frontier=new
    return frozenset(S)
def count_ok(ws,N):
    ok=[True]+[False]*N
    for s in range(1,N+1): ok[s]=any(s>=w and ok[s-w] for w in set(ws))
    return ok[N]
def colorable(R,K,n):
    Kl=sorted(K); groups={}
    for r in R:
        key=min(sub(r,k,n) for k in Kl); groups.setdefault(key,[]).append(r)
    rows={}
    for g,rs in groups.items():
        A=[sub(rs[0],h,n) for h in rs]
        for t in Kl: rows[(g,t)]=frozenset(add(t,a,n) for a in A)
    X={x:set() for x in Kl}
    for r,P in rows.items():
        for x in P: X[x].add(r)
    def solve(unc):
        if not unc: return True
        x=min(unc,key=lambda c:sum(1 for r in X[c] if rows[r]<=unc))
        for r in X[x]:
            if rows[r]<=unc and solve(unc-rows[r]): return True
        return False
    return solve(frozenset(Kl))
