def balanced(v,n,lam): c=Counter(x%n for x in v); return all(c[a]==lam for a in range(n))
def candidates(n,N,lam):
    out=[]
    # first coordinate 0; multiset with value 0 appearing lam-1 more times, others lam
    base=[0]*(lam-1)+[a for a in range(1,n) for _ in range(lam)]
    for perm in set(itertools.permutations(base)) if len(base)<=9 else []:
        out.append((0,)+perm)
    return out
def candidates_fast(n,N,lam):
    res=[]
    def rec(prefix,counts):
        if len(prefix)==N: res.append(tuple(prefix)); return
        for a in range(n):
            if counts[a]>0:
                counts[a]-=1; prefix.append(a); rec(prefix,counts); prefix.pop(); counts[a]+=1
    counts=[lam]*n; counts[0]-=1
    rec([0],counts); return res
